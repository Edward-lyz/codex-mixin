function preferredLang() {
  let saved = null;
  try { saved = localStorage.getItem(LANG_KEY); } catch { /* private mode follows the browser */ }
  if (saved === "zh" || saved === "en") return saved;
  return (navigator.languages || [navigator.language]).some((lang) => /^zh\b/i.test(lang || "")) ? "zh" : "en";
}

const LANG = preferredLang();

function t(text, ...args) {
  const template = LANG === "en" && Object.hasOwn(EN, text) ? EN[text] : text;
  return args.length ? template.replace(/\{(\d+)\}/g, (match, index) => (index < args.length ? String(args[index]) : match)) : template;
}

function savedLang() {
  try { return localStorage.getItem(LANG_KEY) || "auto"; } catch { return "auto"; }
}

function setLang(value) {
  try {
    if (value === "auto") localStorage.removeItem(LANG_KEY);
    else localStorage.setItem(LANG_KEY, value);
  } catch { /* private mode keeps the browser language */ }
  window.location.reload();
}

// index.html is static Chinese markup. This deferred script runs after parsing
// and before app.js, so the static text is translated before the app starts.
function translateDocument() {
  document.documentElement.lang = LANG === "en" ? "en" : "zh-CN";
  if (LANG !== "en") return;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (text && Object.hasOwn(EN, text)) node.nodeValue = node.nodeValue.replace(text, EN[text]);
  }
  for (const element of document.querySelectorAll("[aria-label], [title], [placeholder]")) {
    for (const name of ["aria-label", "title", "placeholder"]) {
      const value = element.getAttribute(name);
      if (value && Object.hasOwn(EN, value)) element.setAttribute(name, EN[value]);
    }
  }
  document.title = t(document.title);
}

